import { converter } from "culori";
import { TOKEN_NAMES, type Theme, type TokenMap } from "./theme";

export interface CssOptions {
  /** base radius, default 0.625rem (shadcn) */
  radius?: string;
}

const toOklch = converter("oklch");
const num = (n: number, digits: number) => String(+n.toFixed(digits));

/** `#rrggbb` -> `oklch(L C h)`; precise enough to round-trip to the same 8-bit hex. */
export function toOklchCss(hex: string): string {
  const c = toOklch(hex)!;
  const chroma = c.c < 1e-4 ? 0 : c.c;
  return `oklch(${num(c.l, 4)} ${num(chroma, 4)} ${chroma === 0 ? 0 : num(c.h ?? 0, 2)})`;
}

const RADII: [string, string][] = [["sm", "calc(var(--radius) * 0.6)"], ["md", "calc(var(--radius) * 0.8)"], ["lg", "var(--radius)"], ["xl", "calc(var(--radius) * 1.4)"], ["2xl", "calc(var(--radius) * 1.8)"], ["3xl", "calc(var(--radius) * 2.2)"], ["4xl", "calc(var(--radius) * 2.6)"]];

const block = (selector: string, lines: string[]) => `${selector} {\n${lines.map((l) => `  ${l}`).join("\n")}\n}\n`;
const vars = (t: TokenMap) => TOKEN_NAMES.map((k) => `--${k}: ${toOklchCss(t[k])};`);

/**
 * shadcn/ui + Tailwind v4 stylesheet: `:root` (light), `.dark`, and `@theme inline` mapping every token to `--color-*`.
 * Variable names match shadcn's; tokens beyond shadcn's list (primary-hover, destructive-foreground, success-*, ...)
 * are emitted and mapped the same way (shadcn "Adding New Tokens").
 */
export function toCss(theme: Theme, { radius = "0.625rem" }: CssOptions = {}): string {
  return [
    "/* generated by gennex-color: do not edit */",
    block(":root", [`--radius: ${radius};`, ...vars(theme.light)]),
    block(".dark", vars(theme.dark)),
    block("@theme inline", [...TOKEN_NAMES.map((k) => `--color-${k}: var(--${k});`), ...RADII.map(([n, v]) => `--radius-${n}: ${v};`)]),
  ].join("\n");
}

/**
 * Only the variables (no `@theme`, no radius), for a stylesheet that is injected at runtime. `light` and `dark` are the
 * selectors that should carry each mode.
 */
export function toRuntimeCss(theme: Theme, sel: { light: string; dark: string }): string {
  return [block(sel.light, vars(theme.light)), block(sel.dark, vars(theme.dark))].join("\n");
}
